#!/usr/bin/env node
/* Builds the lean package for judges / the public repository: ONLY what is needed to
 * understand, run and evaluate the project. No logs, reports, evidence, drafts, build
 * output, binaries or secrets.
 *
 *   node tools/make-submission-zip.js              -> ./AiCafe-submission.zip
 *   node tools/make-submission-zip.js --dry-run    -> list what would be included
 *   node tools/make-submission-zip.js --out my.zip
 *
 * It is an ALLOW-LIST: a new top-level file or folder is left out until it is added to
 * INCLUDE below. A secret scan stops the build if anything looks like a real credential. */
const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

const args = process.argv.slice(2);
const rootIdx = args.indexOf('--root');
const ROOT = rootIdx >= 0 ? path.resolve(args[rootIdx + 1]) : path.resolve(__dirname, '..');
const DRY = args.includes('--dry-run');
const outIdx = args.indexOf('--out');
const OUT = path.resolve(process.cwd(), outIdx >= 0 ? args[outIdx + 1] : 'AiCafe-submission.zip');
const STAGE = path.join(ROOT, '_submission-stage');

// Top-level entries that belong in the package.
const INCLUDE = [
  'README.md', 'LICENSE', 'CONTRIBUTING.md', 'ARCHITECTURE.md', 'DEPLOYMENT.md', 'ENVIRONMENT.md',
  // Demo documents judges are pointed to from docs/JUDGING.md and docs/screenshots/README.md.
  'DEMO_CHECKLIST.md', 'DEMO_VIDEO_SCRIPT.md',
  'openapi.json', 'render.yaml', '.gitignore', '.github', 'docs', 'postman', 'source',
];
// Excluded anywhere in the tree.
const DIR_EXCLUDE = new Set([
  'node_modules', 'dist', 'build', 'coverage', '.git', '.dart_tool', '.gradle', '.idea', '.vscode',
  'Pods', '.symlinks', 'ephemeral', 'archive', '_submission-stage', '.pub-cache', '.pub',
  'security-remediation',
]);
const FILE_EXCLUDE = [
  /\.log$/i, /\.(apk|aab|ipa|zip|jks|keystore|p12|pem)$/i, /\.iml$/i, /^\.DS_Store$/, /^Thumbs\.db$/i,
  /^local\.properties$/, /^key\.properties$/, /^\.env(\..*)?$/, /\.env$/i, /^\.envrc$/, /^env\.(local|production|development|prod|dev)$/i,
  // Generated per machine by Flutter (absolute local paths, ignored by the project's own .gitignore) and the
  // Gradle wrapper (regenerated by `flutter build`; an unscannable binary).
  /^Generated\.xcconfig$/, /^flutter_export_environment\.sh$/, /^GeneratedPluginRegistrant\.(h|m|java)$/,
  /^gradle-wrapper\.jar$/, /^gradlew(\.bat)?$/,
  /^\.?secrets?\.(json|ya?ml|txt)$/i, /^credentials.*\.json$/i, /^service-?account.*\.json$/i, /^npm-debug\.log/, /\.tmp$/i,
  // Generated by `flutter pub get`; it embeds ABSOLUTE local paths (the developer's pub cache) and
  // must never reach a reader's machine. It is already gitignored, but this walker reads the disk.
  /^\.flutter-plugins(-dependencies)?$/,
  // working drafts that are for the author, not for the reader of the repository
  /^SUBMISSION\.md$/, /^devpost-testing-instructions\.md$/, /^DEPLOY_AND_DEMO_RUNBOOK\.md$/,
  // internal work logs / audit output
  /^EXIT_REPORT.*\.md$/, /_REPORT\.md$/, /^STEP\d+_.*\.md$/, /^PHASE\d+_.*\.md$/, /^npm-audit.*\.json$/, /^audit-.*\.json$/, /^test-results.*\.json$/,
];
const FILE_KEEP = [/^\.env\.example$/, /^\.env\.render\.example$/];
// Every kind of real environment / credential file: .env, .env.local, .env.production, prod.env, .envrc,
// env.local, secrets.json, credentials*.json, service-account*.json. Only the two *.example files are allowed.
const ENV_NAME = /(^|\/)(\.env(\..+)?|[^/]*\.env|\.envrc|env\.(local|production|development|prod|dev)|\.?secrets?\.(json|ya?ml|txt)|credentials[^/]*\.json|service-?account[^/]*\.json)$/i;
const ENV_ALLOWED = /(^|\/)\.env\.(render\.)?example$/;
const isForbiddenEnvFile = (rel) => ENV_NAME.test(rel) && !ENV_ALLOWED.test(rel);

const SECRET_PATTERNS = [
  [/AIza[0-9A-Za-z_-]{35}/, 'Google API key'],
  [/\bsk-[A-Za-z0-9_-]{20,}/, 'OpenAI-style key'],
  [/\bgsk_[A-Za-z0-9]{20,}/, 'Groq key'],
  [/\bcsk-[A-Za-z0-9]{20,}/, 'Cerebras-style key'],
  [/\bgh[pousr]_[A-Za-z0-9]{30,}/, 'GitHub token'],
  [/-----BEGIN (?:[A-Z]+ )?PRIVATE KEY-----/, 'private key'],
  [/postgres(?:ql)?:\/\/[^:\s'"]+:[^@\s'"]{4,}@(?!localhost|127\.0\.0\.1|HOST|host|example)[^\s'"/]+/, 'database URL with credentials'],
  [/(?:PAYPAL_CLIENT_ID|PAYPAL_CLIENT_SECRET|PAYPAL_WEBHOOK_ID|OPS_COPILOT_KEY|MANDATE_SIGNING_KEY|DATABASE_URL|OPENAI_API_KEY|GEMINI_API_KEY|GROQ_API_KEY|CEREBRAS_API_KEY|OPENROUTER_API_KEY|AUTOMATION_WEBHOOK_SECRET)\s*[=:]\s*['"]?([^\s#'"]+)/, 'credential assignment'],
];
// Judged on the matched VALUE only. A line that merely contains the word "test" or a comment no longer
// hides a real credential next to it.
// Test code carries deliberate fake keys (redaction fixtures). They are accepted ONLY when the value carries an
// unmistakable fake marker; anything else in a tests/ folder is scanned exactly like production code.
const FAKE_FIXTURE = /abcDEF|A1b2C3d4|secret-|s3cret|live-123|fake|dummy|not-a-key|test-secret|user:pass@|x:y@/i;
const PLACEHOLDER = /^(your[-_]|example|changeme|replace|dummy|placeholder|x{3,}|<|\$\{|\$\(|\.\.\.|secret-|merchant-key|test[-_])|(your[-_]|<[a-z_-]+>|\.\.\.$)/i;

// Package-only exclusions by exact path (the files stay on disk; the owner decides about deleting them).
// Merged into other documents / superseded by the root copy; see the merge plan in the audit report.
const EXCLUDE_PATHS = new Set([
  'docs/JURY_REVIEW.md',
  'docs/VERIFICATION_PROMPTS.md',
  'source/apps/backend/ARCHITECTURE.md',
  'source/apps/backend/DEPLOYMENT.md',
  'source/apps/backend/ENVIRONMENT.md',
  'source/apps/backend/render.yaml',
]);

function excluded(name, isDir) {
  if (isDir) return DIR_EXCLUDE.has(name);
  if (FILE_KEEP.some((re) => re.test(name))) return false;
  return FILE_EXCLUDE.some((re) => re.test(name));
}

const files = [];
const skippedSymlinks = [];
function walk(abs, rel) {
  for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
    const childAbs = path.join(abs, entry.name);
    const childRel = path.posix.join(rel, entry.name);
    if (entry.isSymbolicLink()) { skippedSymlinks.push(childRel); continue; }
    if (entry.isDirectory()) {
      if (!excluded(entry.name, true)) walk(childAbs, childRel);
    } else if (!excluded(entry.name, false) && !EXCLUDE_PATHS.has(childRel)) {
      files.push(childRel);
    }
  }
}
for (const name of INCLUDE) {
  const abs = path.join(ROOT, name);
  if (!fs.existsSync(abs)) continue;
  if (fs.statSync(abs).isDirectory()) walk(abs, name);
  else if (!excluded(name, false) || name === '.gitignore') files.push(name);
}
files.sort();

// Hard guard, independent of the allow-list and the exclusion regexes: no real env/credential file may be listed.
const envLeaks = files.filter(isForbiddenEnvFile);
if (envLeaks.length) {
  console.error('STOP: env/credential file(s) in the package list: ' + envLeaks.join(', '));
  process.exit(3);
}

// ---- secret scan (never prints the matched value) ----
function scanText(rel, text, out) {
  const inTests = /(^|\/)tests?\//.test(rel);
  text.split(/\r?\n/).forEach((line, i) => {
    for (const [re, label] of SECRET_PATTERNS) {
      const m = re.exec(line);
      if (!m) continue;
      const value = m[1] !== undefined ? m[1] : m[0];
      if (inTests && FAKE_FIXTURE.test(value)) continue;
      if (PLACEHOLDER.test(value)) continue;
      // Assignments in docs/code often carry a schema, an env lookup or a local dev URL, not a credential.
      if (label === 'credential assignment' &&
          (value.length < 16 || /…|localhost|127\.0\.0\.1|^(process\.|z\.|import\.)|^[A-Za-z_.]+\(|^[A-Za-z_]+(\.[A-Za-z_]+)+[;,)]*$|local[-_]/i.test(value))) continue;
      out.push(`${rel}:${i + 1}  looks like a ${label}`);
    }
  });
}
// Nothing is skipped silently: text of any size up to MAX_SCAN is scanned; binaries must be a known image/font
// type (anything else stops the build) and are also scanned as strings; symlinks are listed.
const MAX_SCAN = 25 * 1024 * 1024;
const BINARY_OK = /\.(png|jpe?g|gif|webp|ico|ttf|otf|woff2?)$/i;
const coverage = { text: 0, binary: 0 };

// Independent cross-check that does not depend on any pattern: the actual values found in the real env /
// credential files on disk are searched for in every packaged file and again in the finished archive.
// Only the variable name and the file path are ever printed, never a value.
const fingerprints = [];
const fingerprintSources = new Set();
function collectFingerprints() {
  (function walkDisk(abs, rel) {
    for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
      if (e.isSymbolicLink()) continue;
      const cAbs = path.join(abs, e.name);
      const cRel = rel ? rel + '/' + e.name : e.name;
      if (e.isDirectory()) {
        if (!['node_modules', '.git', '_submission-stage', '.dart_tool', 'build', 'dist'].includes(e.name)) walkDisk(cAbs, cRel);
        continue;
      }
      if (!isForbiddenEnvFile(cRel)) continue;
      let text;
      try { text = fs.readFileSync(cAbs, 'utf8'); } catch (_) { continue; }
      fingerprintSources.add(cRel);
      const add = (name, raw) => {
        // Only variables that look like credentials: AI_PROVIDER_ORDER or FLUTTER_ROOT are configuration, not secrets.
        if (!/KEY|SECRET|TOKEN|PASS|PWD|CREDENTIAL|PRIVATE|SIGNING|DATABASE_URL|WEBHOOK_ID|CLIENT_ID/i.test(name)) return;
        const value = String(raw).trim().replace(/^(['"])(.*)\1$/, '$2');
        if (value.length < 12 || /^(true|false|null)$/i.test(value) || /localhost|127\.0\.0\.1/i.test(value)) return;
        if (PLACEHOLDER.test(value)) return;
        fingerprints.push({ name, value, source: cRel });
      };
      for (const line of text.split(/\r?\n/)) {
        const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
        if (m && !/^\s*#/.test(line)) add(m[1], m[2].replace(/\s+#.*$/, ''));
      }
      const jsonRe = /"([A-Za-z_][\w-]*)"\s*:\s*"([^"]{16,})"/g;
      let jm;
      while ((jm = jsonRe.exec(text))) add(jm[1], jm[2]);
    }
  })(ROOT, '');
}
collectFingerprints();
function fingerprintScan(rel, buf, out) {
  for (const fp of fingerprints) {
    if (buf.includes(fp.value)) out.push(`${rel}  contains the value of ${fp.name} from ${fp.source}`);
  }
}
function scanFile(rel, abs, out) {
  const size = fs.statSync(abs).size;
  if (size > MAX_SCAN) { out.push(`${rel}  is larger than 25 MB and cannot be scanned`); return; }
  const buf = fs.readFileSync(abs);
  fingerprintScan(rel, buf, out);
  if (buf.includes(0)) {
    coverage.binary++;
    if (!BINARY_OK.test(rel)) out.push(`${rel}  is a binary file of a type that is not allowed in the package`);
    scanText(rel, buf.toString('latin1'), out); // printable strings inside the binary
    return;
  }
  coverage.text++;
  scanText(rel, buf.toString('utf8'), out);
}
const findings = [];
for (const rel of files) scanFile(rel, path.join(ROOT, rel), findings);
console.log(`Scan coverage: ${coverage.text} text files, ${coverage.binary} binary files (image/font types only, also scanned as strings), nothing skipped by size.`);
console.log(fingerprints.length
  ? `Value cross-check armed: ${fingerprints.length} value(s) from ${fingerprintSources.size} real env/credential file(s) on disk are searched for in the package (names only are printed).`
  : 'Value cross-check: no real env/credential file with usable values found on disk, nothing to cross-check.');
if (skippedSymlinks.length) console.log(`Symlinks left out (never followed): ${skippedSymlinks.join(', ')}`);

const top = new Map();
let total = 0;
for (const rel of files) {
  const size = fs.statSync(path.join(ROOT, rel)).size;
  total += size;
  const key = rel.split('/')[0];
  const t = top.get(key) || { n: 0, size: 0 };
  t.n++; t.size += size; top.set(key, t);
}
const mb = (n) => (n / 1048576).toFixed(2) + ' MB';
console.log(`Files: ${files.length}   Size (uncompressed): ${mb(total)}`);
for (const [k, v] of top) console.log(`  ${k.padEnd(18)} ${String(v.n).padStart(5)} files  ${mb(v.size)}`);
console.log('Largest files:');
files
  .map((rel) => [rel, fs.statSync(path.join(ROOT, rel)).size])
  .sort((a, b) => b[1] - a[1])
  .slice(0, 8)
  .forEach(([rel, size]) => console.log(`  ${mb(size).padStart(9)}  ${rel}`));
const skippedTop = fs.readdirSync(ROOT).filter((n) => !INCLUDE.includes(n) && n !== '.git' && n !== '_submission-stage');
console.log(`Left out (top level): ${skippedTop.join(', ') || '(none)'}`);

// Test hook for tools/make-submission-zip.selftest.js ONLY: needs BOTH the variable and the flag, so it cannot be hit by accident.
const SKIP_PRESCAN = process.env.AICAFE_SELFTEST === '1' && args.includes('--selftest-skip-prescan');
if (findings.length && !SKIP_PRESCAN) {
  console.error('\nSTOP: possible secrets found. Fix or remove them, then run again:');
  findings.forEach((f) => console.error('  ' + f));
  process.exit(2);
}
if (DRY) {
  console.log('\n--dry-run: nothing written. Add --list to print every file.');
  if (args.includes('--list')) files.forEach((f) => console.log(f));
  process.exit(0);
}

let run;
try {
fs.rmSync(STAGE, { recursive: true, force: true });
for (const rel of files) {
  const dest = path.join(STAGE, 'AiCafe', rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(ROOT, rel), dest);
}
fs.rmSync(OUT, { force: true });
// Windows 10+ ships bsdtar (can write .zip); elsewhere use zip.
// Resolve bsdtar EXPLICITLY: under Git Bash `tar` is GNU tar, which reads a "C:\..." -f argument as
// a remote host ("Cannot connect to C: resolve failed"), so the plain name is not reliable on Windows.
run =
  process.platform === 'win32'
    ? (() => {
        const bsdtar = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe');
        const bin = fs.existsSync(bsdtar) ? bsdtar : 'tar';
        return spawnSync(bin, ['-a', '-c', '-f', OUT, '-C', STAGE, 'AiCafe'], { stdio: 'inherit' });
      })()
    : spawnSync('zip', ['-qr', OUT, 'AiCafe'], { cwd: STAGE, stdio: 'inherit' });
} finally {
  fs.rmSync(STAGE, { recursive: true, force: true });
}
if (run.status !== 0) {
  console.error('Could not create the zip (needs bsdtar on Windows or `zip` on Linux/macOS).');
  process.exit(1);
}
// ---- verify the finished archive: extract it again and check what is REALLY inside ----
const VERIFY = fs.mkdtempSync(path.join(os.tmpdir(), 'aicafe-zipcheck-'));
const bad = [];
let extracted = 0;
try {
  const winTar = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe');
  const unpack =
    process.platform === 'win32'
      ? spawnSync(fs.existsSync(winTar) ? winTar : 'tar', ['-xf', OUT, '-C', VERIFY], { stdio: 'inherit' })
      : spawnSync('unzip', ['-q', OUT, '-d', VERIFY], { stdio: 'inherit' });
  if (unpack.status !== 0) {
    bad.push('could not re-open the archive for verification');
  } else {
    const seen = new Set();
    (function walkOut(abs, rel) {
      for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
        const cAbs = path.join(abs, e.name);
        const cRel = rel ? rel + '/' + e.name : e.name;
        if (e.isDirectory()) { walkOut(cAbs, cRel); continue; }
        extracted++;
        seen.add(cRel);
        if (isForbiddenEnvFile(cRel)) bad.push(`${cRel}  is an env/credential file inside the archive`);
        scanFile(cRel, cAbs, bad); // patterns AND the real env values, applied to the extracted copy
      }
    })(VERIFY, '');
    const expected = new Set(files.map((f) => 'AiCafe/' + f));
    for (const f of seen) if (!expected.has(f)) bad.push(`${f}  is in the archive but was not on the package list`);
    for (const f of expected) if (!seen.has(f)) bad.push(`${f}  is on the package list but missing from the archive`);
  }
} finally {
  fs.rmSync(VERIFY, { recursive: true, force: true });
}
if (bad.length) {
  fs.rmSync(OUT, { force: true });
  console.error('\nSTOP: the finished archive failed verification and was deleted:');
  bad.forEach((f) => console.error('  ' + f));
  process.exit(4);
}
console.log(`Archive re-opened and verified: ${extracted} files, no env/credential files, no secret patterns.`);
console.log(`\nWrote ${OUT}  (${mb(fs.statSync(OUT).size)})`);
