#!/usr/bin/env node
'use strict';
// Generates web CSS + Flutter Dart constants from source/design/tokens.json.
// Pure Node, no dependencies. `render()` is exported so a unit test can prove the committed
// output files are in sync with tokens.json.
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const TOKENS = path.join(ROOT, 'design', 'tokens.json');
const OUT_CSS = path.join(ROOT, 'apps', 'backend', 'public', 'tokens.css');
const OUT_DART = path.join(ROOT, 'apps', 'flutter_app', 'lib', 'theme', 'tokens.g.dart');

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const hexToRgb = (h) => {
  const n = parseInt(h.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const dartColor = (h) => `Color(0xFF${h.slice(1).toUpperCase()})`;

function cssVars(set, indent) {
  return Object.entries(set)
    .map(([k, v]) => `${indent}--ac-${kebab(k)}: ${v};`)
    .join('\n');
}

function renderCss(t) {
  const [r, g, b] = hexToRgb(t.light.coral);
  return `/* GENERATED by tools/gen-design-tokens.js from design/tokens.json. DO NOT EDIT BY HAND. */
:root {
${cssVars(t.light, '  ')}
${Object.entries(t.category).map(([k, v]) => `  --ac-cat-${k}: ${v};`).join('\n')}
  --ac-radius-card: ${t.shape.radiusCard}px;
  --ac-radius-control: ${t.shape.radiusControl}px;
  --ac-radius-pill: ${t.shape.radiusPill}px;
  --ac-grad: linear-gradient(135deg, ${t.gradient.from} 0%, ${t.gradient.to} 100%);
  --ac-font: ${t.font.web};

  /* Legacy names used by index.html / dashboard.html / theme.css, mapped onto the shared palette. */
  --bg: var(--ac-canvas);
  --card: var(--ac-surface);
  --ink: var(--ac-ink);
  --mut: var(--ac-muted);
  --line: var(--ac-line);
  --brand: var(--ac-coral-strong);
  --brand-2: var(--ac-coral);
  --brand-ink: #ffffff;
  --on-grad: var(--ac-ink);
  --brand-soft: rgba(${r}, ${g}, ${b}, .18);
  --ok: var(--ac-ok);
  --warn: var(--ac-warn);
  --bad: var(--ac-bad);
  --focus: var(--ac-coral-strong);
}
@media (prefers-color-scheme: dark) {
  :root {
${cssVars(t.dark, '    ')}
    --brand-ink: #1b120e;
    --on-grad: var(--ac-canvas);
    --brand-soft: rgba(255, 158, 133, .18);
    --focus: var(--ac-coral);
  }
}
`;
}

function renderDart(t) {
  const names = Object.keys(t.light);
  const light = names.map((k) => `  static const Color ${k} = ${dartColor(t.light[k])};`).join('\n');
  const dark = names.map((k) => `  static const Color ${k} = ${dartColor(t.dark[k])};`).join('\n');
  const cat = Object.entries(t.category)
    .map(([k, v]) => `  '${k}': ${dartColor(v)},`)
    .join('\n');
  return `// GENERATED by tools/gen-design-tokens.js from design/tokens.json. DO NOT EDIT BY HAND.
// Run \`npm run tokens\` in apps/backend after editing design/tokens.json.
import 'package:flutter/material.dart';

/// Light palette shared 1:1 with the web storefront (public/tokens.css).
abstract final class AcLight {
${light}
}

/// Dark palette shared 1:1 with the web storefront.
abstract final class AcDark {
${dark}
}

/// Pastel tint per catalog category (same values as manifest.json / web).
const Map<String, Color> acCategoryTints = {
${cat}
};

abstract final class AcShape {
  static const double radiusCard = ${t.shape.radiusCard};
  static const double radiusControl = ${t.shape.radiusControl};
  static const double radiusPill = ${t.shape.radiusPill};
}

abstract final class AcGradient {
  static const Color from = ${dartColor(t.gradient.from)};
  static const Color to = ${dartColor(t.gradient.to)};
  static const LinearGradient coral = LinearGradient(
    begin: Alignment.topLeft,
    end: Alignment.bottomRight,
    colors: [from, to],
  );
}
`;
}

function render() {
  const t = JSON.parse(fs.readFileSync(TOKENS, 'utf8'));
  return { css: renderCss(t), dart: renderDart(t), tokens: t };
}

module.exports = { render, OUT_CSS, OUT_DART, TOKENS };

if (require.main === module) {
  const { css, dart } = render();
  fs.writeFileSync(OUT_CSS, css);
  fs.mkdirSync(path.dirname(OUT_DART), { recursive: true });
  fs.writeFileSync(OUT_DART, dart);
  console.log('wrote', path.relative(ROOT, OUT_CSS));
  console.log('wrote', path.relative(ROOT, OUT_DART));
}
